"""Generate src/core/log/enums.ts from python-hearthstone's enums.py.

Usage: python3 -I scripts/gen-enums.py path/to/enums.py > src/core/log/enums.ts
"""
import re
import sys

src = open(sys.argv[1], encoding="utf-8").read()
WANTED = ["GameTag", "Zone", "CardType", "Race", "Step", "PlayState", "BlockType", "State",
          "GameType", "FormatType", "ChoiceType", "MetaDataType", "Mulligan", "CardClass"]
out = ["// AUTO-GENERATED by scripts/gen-enums.py from HearthSim/python-hearthstone enums.py. Do not edit.", ""]
for name in WANTED:
    m = re.search(r"^class %s\(IntEnum\):\n(.*?)(?=^class |\Z)" % name, src, re.M | re.S)
    if not m:
        sys.exit("enum not found: " + name)
    body = m.group(1)
    pairs = []
    seen = set()
    for line in body.splitlines():
        mm = re.match(r"^\t([A-Z_][A-Z0-9_]*) = (-?\d+)\s*(#.*)?$", line)
        if mm:
            key, val = mm.group(1), int(mm.group(2))
            pairs.append((key, val))
    out.append("export const %s: Record<string, number> = {" % name)
    for k, v in pairs:
        out.append("  %s: %d," % (k, v))
    out.append("};")
    # reverse map: first name wins (enums.py lists canonical names first, aliases later)
    out.append("export const %s_BY_ID: Record<number, string> = {" % name)
    for k, v in pairs:
        if v in seen:
            continue
        seen.add(v)
        out.append("  %d: '%s'," % (v, k))
    out.append("};")
    out.append("")
print("\n".join(out))
