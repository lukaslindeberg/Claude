import type { BgCard, BgCardData, Tribe } from '@shared/types';
import bundled from './data/bg-cards.json';

/**
 * Read-only lookup over Battlegrounds card data.
 * Works in Node (main process, tests) and in the browser (renderer, workers).
 */
export class CardDb {
  readonly data: BgCardData;
  private readonly byId = new Map<string, BgCard>();
  private readonly byDbf = new Map<number, BgCard>();

  constructor(data: BgCardData) {
    this.data = data;
    for (const c of data.cards) {
      this.byId.set(c.id, c);
      this.byDbf.set(c.dbfId, c);
    }
  }

  private static _bundled?: CardDb;
  /** Card data bundled with the app (generated by `npm run cards`). */
  static bundled(): CardDb {
    if (!CardDb._bundled) CardDb._bundled = new CardDb(bundled as BgCardData);
    return CardDb._bundled;
  }

  get build(): number {
    return this.data.build;
  }
  get patch(): string | undefined {
    return this.data.patch;
  }
  get size(): number {
    return this.data.cards.length;
  }

  get(cardId: string | undefined): BgCard | undefined {
    return cardId ? this.byId.get(cardId) : undefined;
  }

  getByDbfId(dbfId: number | undefined): BgCard | undefined {
    return dbfId ? this.byDbf.get(dbfId) : undefined;
  }

  /** Display name; falls back to the provided name or the card id. */
  name(cardId: string, fallback?: string): string {
    return this.byId.get(cardId)?.name ?? fallback ?? cardId;
  }

  tribes(cardId: string): Tribe[] {
    return this.byId.get(cardId)?.tribes ?? [];
  }

  tier(cardId: string): number | undefined {
    const c = this.byId.get(cardId);
    return c?.tier ?? (c?.normalId ? this.byId.get(c.normalId)?.tier : undefined);
  }

  /** Base hero id for a (possibly skinned) hero card id. */
  baseHeroId(cardId: string): string {
    let c = this.byId.get(cardId);
    let guard = 0;
    while (c?.skinParentId && guard++ < 5) {
      const parent = this.byId.get(c.skinParentId);
      if (!parent) break;
      c = parent;
    }
    if (c) return c.id;
    // Heuristic for skins missing from data: strip _SKIN_xx suffix.
    return cardId.replace(/_SKIN_[A-Z0-9]+$/i, '');
  }

  goldenOf(cardId: string): string | undefined {
    return this.byId.get(cardId)?.goldenId;
  }

  normalOf(cardId: string): string {
    return this.byId.get(cardId)?.normalId ?? cardId;
  }

  isGolden(cardId: string): boolean {
    return !!this.byId.get(cardId)?.golden;
  }

  /** Current shop-pool minions (non-golden), sorted by tier then name. */
  poolMinions(): BgCard[] {
    return this.data.cards
      .filter((c) => c.pool && c.type === 'MINION' && !c.golden)
      .sort((a, b) => (a.tier ?? 0) - (b.tier ?? 0) || a.name.localeCompare(b.name));
  }

  /** Current tavern spells in the pool. */
  poolSpells(): BgCard[] {
    return this.data.cards
      .filter((c) => c.pool && c.type === 'SPELL')
      .sort((a, b) => (a.tier ?? 0) - (b.tier ?? 0) || a.name.localeCompare(b.name));
  }

  /** Draftable heroes (base versions). */
  heroes(): BgCard[] {
    return this.data.cards.filter((c) => c.type === 'HERO' && c.mechanics.includes('BACON_HERO_CAN_BE_DRAFTED'));
  }

  anomalies(): BgCard[] {
    return this.data.cards.filter((c) => c.type === 'ANOMALY');
  }

  trinkets(): BgCard[] {
    return this.data.cards.filter((c) => c.type === 'TRINKET');
  }

  hasMechanic(cardId: string, mechanic: string): boolean {
    return !!this.byId.get(cardId)?.mechanics.includes(mechanic);
  }
}

/** URLs for card art served by HearthstoneJSON (loaded by the renderer; may be disabled in settings). */
export const cardArt = {
  /** Square-ish art crop (good for hero portraits and minion bubbles). */
  crop: (cardId: string) => `https://art.hearthstonejson.com/v1/256x/${cardId}.jpg`,
  /** Full card render. */
  render: (cardId: string, locale = 'enUS') =>
    `https://art.hearthstonejson.com/v1/render/latest/${locale}/256x/${cardId}.png`,
  /** Battlegrounds-style render (tier pip, no mana cost); 512x for large or high-DPI tooltips. */
  bgsRender: (cardId: string, locale = 'enUS', size: 256 | 512 = 256) =>
    `https://art.hearthstonejson.com/v1/bgs/latest/${locale}/${size}x/${cardId}.png`,
  /** Deck-tracker style tile. */
  tile: (cardId: string) => `https://art.hearthstonejson.com/v1/tiles/${cardId}.png`,
};
